CREATE OR REPLACE VIEW vw_oferta AS
SELECT pl.tb_periodo_letivo_ano AS ano, pl.tb_periodo_letivo_semestre AS semestre,
       d.tb_disciplina_codigo AS codigo_disciplina, d.tb_disciplina_nome AS disciplina,
       t.tb_turma_codigo AS codigo_turma, t.tb_turma_turno AS turno, p.tb_pessoa_nome AS professor
FROM tb_turma t
JOIN tb_disciplina d ON t.tb_disciplina_id = d.tb_disciplina_id
JOIN tb_periodo_letivo pl ON t.tb_periodo_letivo_id = pl.tb_periodo_letivo_id
JOIN tb_professor prof ON t.tb_professor_id = prof.tb_professor_id
JOIN tb_pessoa p ON prof.tb_professor_id = p.tb_pessoa_id;

CREATE OR REPLACE VIEW vw_vagas AS
SELECT t.tb_turma_id AS id_turma, pl.tb_periodo_letivo_ano AS ano, pl.tb_periodo_letivo_semestre AS semestre,
       t.tb_turma_codigo AS codigo_turma, d.tb_disciplina_nome AS disciplina,
       t.tb_turma_vagas AS vagas_totais, COUNT(m.tb_matricula_turma_id) AS matriculas_efetivadas,
       t.tb_turma_vagas - COUNT(m.tb_matricula_turma_id) AS vagas_disponiveis
FROM tb_turma t
JOIN tb_disciplina d ON t.tb_disciplina_id = d.tb_disciplina_id
JOIN tb_periodo_letivo pl ON t.tb_periodo_letivo_id = pl.tb_periodo_letivo_id
LEFT JOIN tb_matricula_turma m ON t.tb_turma_id = m.tb_turma_id AND m.tb_matricula_turma_status IN ('MATRICULADA', 'CONCLUIDA')
GROUP BY t.tb_turma_id, pl.tb_periodo_letivo_ano, pl.tb_periodo_letivo_semestre, t.tb_turma_codigo, d.tb_disciplina_nome, t.tb_turma_vagas;

CREATE OR REPLACE VIEW vw_historico AS
SELECT a.tb_aluno_matricula AS matricula, p.tb_pessoa_nome AS nome_aluno,
       pl.tb_periodo_letivo_ano AS ano, pl.tb_periodo_letivo_semestre AS semestre,
       d.tb_disciplina_codigo AS codigo_disciplina, d.tb_disciplina_nome AS disciplina,
       h.tb_historico_media_final AS media_final, h.tb_historico_frequencia AS frequencia, h.tb_historico_situacao AS situacao
FROM tb_aluno a
JOIN tb_pessoa p ON a.tb_aluno_id = p.tb_pessoa_id
JOIN tb_aluno_curriculo ac ON a.tb_aluno_id = ac.tb_aluno_id
JOIN tb_matricula_turma m ON ac.tb_aluno_curriculo_id = m.tb_aluno_curriculo_id
JOIN tb_turma t ON m.tb_turma_id = t.tb_turma_id
JOIN tb_disciplina d ON t.tb_disciplina_id = d.tb_disciplina_id
JOIN tb_periodo_letivo pl ON t.tb_periodo_letivo_id = pl.tb_periodo_letivo_id
JOIN tb_historico h ON m.tb_matricula_turma_id = h.tb_matricula_turma_id;

CREATE MATERIALIZED VIEW mvw_indicadores AS
SELECT pl.tb_periodo_letivo_ano AS ano, pl.tb_periodo_letivo_semestre AS semestre,
       d.tb_disciplina_nome AS disciplina, COUNT(h.tb_historico_id) AS total_avaliacoes,
       ROUND(AVG(h.tb_historico_media_final), 2) AS media_geral_turma,
       ROUND(AVG(h.tb_historico_frequencia), 2) AS frequencia_media,
       ROUND((SUM(CASE WHEN h.tb_historico_situacao = 'APROVADO' THEN 1 ELSE 0 END)::numeric / NULLIF(COUNT(h.tb_historico_id), 0)) * 100, 2) AS taxa_aprovacao_perc
FROM tb_historico h
JOIN tb_matricula_turma m ON h.tb_matricula_turma_id = m.tb_matricula_turma_id
JOIN tb_turma t ON m.tb_turma_id = t.tb_turma_id
JOIN tb_disciplina d ON t.tb_disciplina_id = d.tb_disciplina_id
JOIN tb_periodo_letivo pl ON t.tb_periodo_letivo_id = pl.tb_periodo_letivo_id
GROUP BY pl.tb_periodo_letivo_ano, pl.tb_periodo_letivo_semestre, d.tb_disciplina_nome
WITH NO DATA;
CREATE UNIQUE INDEX idx_mvw_indicadores_unq ON mvw_indicadores(ano, semestre, disciplina);

