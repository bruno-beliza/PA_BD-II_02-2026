-- 1.7 - AUTOMAÇÃO: TRIGGER DE REGRAS ACADÊMICAS
-- ============================================================================
CREATE OR REPLACE FUNCTION fn_calcular_nota()
RETURNS TRIGGER AS $$
DECLARE
    v_a1 NUMERIC(4,2) := COALESCE(NEW.tb_nota_a1, 0);
    v_a2 NUMERIC(4,2) := COALESCE(NEW.tb_nota_a2, 0);
    v_media_base NUMERIC(4,2);
    v_freq NUMERIC(5,2);
BEGIN
    -- Busca a frequência atualizada da matrícula, se existir
    SELECT tb_frequencia_percentual INTO v_freq
    FROM tb_frequencia
    WHERE tb_matricula_turma_id = NEW.tb_matricula_turma_id;

    -- Cálculo da Média Base (A1 40% + A2 60%)
    v_media_base := (v_a1 * 0.4) + (v_a2 * 0.6);

    -- Regra de Substituição P3: se a base for menor que 5 e a P3 existir, substitui a menor
    IF v_media_base < 5.00 AND NEW.tb_nota_p3 IS NOT NULL THEN
        IF v_a1 < v_a2 THEN
            v_a1 := NEW.tb_nota_p3;
        ELSE
            v_a2 := NEW.tb_nota_p3;
        END IF;
        NEW.tb_nota_media_final := ROUND((v_a1 * 0.4) + (v_a2 * 0.6), 2);
    ELSE
        NEW.tb_nota_media_final := ROUND(v_media_base, 2);
    END IF;

    -- Definição da Situação
    IF v_freq IS NOT NULL AND v_freq < 75.00 THEN
        NEW.tb_nota_situacao := 'REPROVADO_FREQUENCIA';
    ELSIF NEW.tb_nota_media_final >= 5.00 THEN
        NEW.tb_nota_situacao := 'APROVADO';
    ELSE
        NEW.tb_nota_situacao := 'REPROVADO';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_antes_nota
BEFORE INSERT OR UPDATE ON tb_nota
FOR EACH ROW
EXECUTE FUNCTION fn_calcular_nota();

