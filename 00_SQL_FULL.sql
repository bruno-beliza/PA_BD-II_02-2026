-- Plano de matrículas (tabela temporária, removida no final da carga).
-- Cada aluno ingressa no semestre "e" e cursa as disciplinas 1, 2, ..., l EM SEQUÊNCIA,
-- uma por semestre (disciplina j no semestre e + j - 1). Assim, toda matrícula numa
-- disciplina é precedida, em semestre anterior, pela matrícula no seu pré-requisito.
--   alunos  1-10  : ingresso em 2023/2, cursam 6 disciplinas ->  60 matrículas
--   alunos 11-20  : ingresso em 2024/1, cursam 5 disciplinas ->  50 matrículas
--   alunos 21-35  : ingresso em 2024/2, cursam 4 disciplinas ->  60 matrículas
--   alunos 36-55  : ingresso em 2025/1, cursam 3 disciplinas ->  60 matrículas
--   alunos 56-80  : ingresso em 2025/2, cursam 2 disciplinas ->  50 matrículas
--   alunos 81-100 : ingresso em 2026/1, cursam 1 disciplina  ->  20 matrículas
--                                                      TOTAL  = 300 matrículas
CREATE TEMP TABLE plano_aluno AS
SELECT n,
       CASE WHEN n <= 10 THEN 1 WHEN n <= 20 THEN 2 WHEN n <= 35 THEN 3
            WHEN n <= 55 THEN 4 WHEN n <= 80 THEN 5 ELSE 6 END AS e,
       CASE WHEN n <= 10 THEN 6 WHEN n <= 20 THEN 5 WHEN n <= 35 THEN 4
            WHEN n <= 55 THEN 3 WHEN n <= 80 THEN 2 ELSE 1 END AS l
FROM generate_series(1, 100) AS g(n);

