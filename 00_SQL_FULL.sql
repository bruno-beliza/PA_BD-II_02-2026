-- Impede sobreposição de horários na mesma sala e dia da semana.
-- btree_gist permite combinar igualdade (sala/dia) e sobreposição de intervalos.
CREATE EXTENSION IF NOT EXISTS btree_gist;
ALTER TABLE tb_turma_horario
  ADD CONSTRAINT ex_turma_horario_sem_sobreposicao
  EXCLUDE USING gist (
    tb_sala_id WITH =,
    tb_turma_horario_dia_semana WITH =,
    (tsrange(
      DATE '2000-01-03' + tb_turma_horario_inicio,
      DATE '2000-01-03' + tb_turma_horario_fim,
      '[)'
    )) WITH &&
  );

