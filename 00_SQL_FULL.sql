-- Turmas: só existem as ofertas (disciplina, semestre) em que algum aluno do plano se matricula
-- (id = (semestre - 1) * 6 + disciplina), mais a turma 37, ofertada para o semestre corrente
-- (2026/2) e AINDA SEM MATRÍCULAS. É ela que faz a junção externa da Consulta 3 retornar
-- uma linha com zero matrículas.
INSERT INTO tb_turma
  (tb_turma_id, tb_turma_codigo, tb_disciplina_id, tb_periodo_letivo_id, tb_professor_id, tb_turma_turno, tb_turma_vagas)
SELECT n,
       'T' || LPAD(n::text, 3, '0'),
       CASE WHEN n <= 36 THEN (n - 1) % 6 + 1 ELSE 1 END,
       CASE WHEN n <= 36 THEN (n - 1) / 6 + 1 ELSE 7 END,
       100 + CASE WHEN n <= 36 THEN (n - 1) % 6 + 1 ELSE 1 END,
       CASE WHEN n % 2 = 0 THEN 'NOTURNO'::turno_turma ELSE 'MATUTINO'::turno_turma END,
       60
FROM generate_series(1, 37) AS g(n)
WHERE g.n = 37
   OR EXISTS (
        SELECT 1 FROM plano_aluno p
        WHERE p.e = ((g.n - 1) / 6 + 1) - ((g.n - 1) % 6 + 1) + 1   -- semestre - disciplina + 1
          AND p.l >= (g.n - 1) % 6 + 1
      );

-- Horários: a restrição EXCLUDE considera apenas sala + dia + faixa de horário (não o período
-- letivo), então cada turma recebe uma combinação sala/dia/faixa distinta (id da turma = n).
-- 30 combinações (6 salas x 5 dias) na faixa das 08:00 e as demais na faixa das 10:00.
INSERT INTO tb_turma_horario
  (tb_turma_horario_id, tb_turma_id, tb_sala_id, tb_turma_horario_dia_semana, tb_turma_horario_inicio, tb_turma_horario_fim)
SELECT t.tb_turma_id,
       t.tb_turma_id,
       ((t.tb_turma_id - 1) % 6) + 1,
       CASE ((t.tb_turma_id - 1) / 6) % 5
         WHEN 0 THEN 'SEGUNDA'::dia_semana
         WHEN 1 THEN 'TERCA'::dia_semana
         WHEN 2 THEN 'QUARTA'::dia_semana
         WHEN 3 THEN 'QUINTA'::dia_semana
         ELSE 'SEXTA'::dia_semana
       END,
       TIME '08:00' + ((t.tb_turma_id - 1) / 30) * INTERVAL '2 hours',
       TIME '09:40' + ((t.tb_turma_id - 1) / 30) * INTERVAL '2 hours'
FROM tb_turma t;

-- Exatamente 300 matrículas (ver plano_aluno): o aluno cursa a disciplina j no semestre
-- e + j - 1, ou seja, sempre depois do semestre em que cursou o pré-requisito.
INSERT INTO tb_matricula_turma
  (tb_matricula_turma_id, tb_aluno_curriculo_id, tb_turma_id, tb_matricula_turma_data_matricula, tb_matricula_turma_status)
SELECT ROW_NUMBER() OVER (ORDER BY p.n, j.j),
       p.n,
       (p.e + j.j - 2) * 6 + j.j,
       ((pl.tb_periodo_letivo_data_inicio + TIME '09:00') AT TIME ZONE 'America/Sao_Paulo')
         + (p.n % 20) * INTERVAL '1 day',
       'CONCLUIDA'
FROM plano_aluno p
CROSS JOIN LATERAL generate_series(1, p.l) AS j(j)
JOIN tb_periodo_letivo pl ON pl.tb_periodo_letivo_id = p.e + j.j - 1;

-- Histórico coerente com a progressão: toda disciplina que NÃO é a última cursada pelo aluno
-- foi APROVADA (senão ele não poderia ter avançado). Só a última disciplina pode ter resultado
-- diferente: aluno com id % 5 = 0 reprova por nota, id % 5 = 1 reprova por frequência,
-- os demais são aprovados. Isso deixa alunos "parados" num ponto da cadeia, o que dá
-- resultados distintos para a Consulta 7.
INSERT INTO tb_historico
  (tb_historico_id, tb_matricula_turma_id, tb_historico_nota_a1, tb_historico_nota_a2,
   tb_historico_nota_p3, tb_historico_frequencia, tb_historico_situacao, tb_historico_media_final)
WITH base AS (
  SELECT m.tb_matricula_turma_id AS mid, ac.tb_aluno_id AS n, t.tb_disciplina_id AS d,
         MAX(t.tb_disciplina_id) OVER (PARTITION BY ac.tb_aluno_id) AS ultima
  FROM tb_matricula_turma m
  JOIN tb_aluno_curriculo ac ON ac.tb_aluno_curriculo_id = m.tb_aluno_curriculo_id
  JOIN tb_turma t ON t.tb_turma_id = m.tb_turma_id
), resultado AS (
  SELECT mid, n, d,
         CASE WHEN d < ultima THEN 'A' WHEN n % 5 = 0 THEN 'N' WHEN n % 5 = 1 THEN 'F' ELSE 'A' END AS res
  FROM base
), notas AS (
  SELECT mid, n, d, res,
         CASE WHEN res = 'N' THEN 5.00 ELSE (6 + ((n + d) % 5))::numeric END AS a1,
         CASE WHEN res = 'N' THEN 5.50 ELSE (6 + ((n * 2 + d) % 5))::numeric END AS a2,
         CASE WHEN res = 'F' THEN (60 + (n % 15))::numeric ELSE (80 + ((n + d) % 21))::numeric END AS freq
  FROM resultado
)
SELECT mid, mid, a1, a2, NULL, freq,
       CASE res WHEN 'A' THEN 'APROVADO'::situacao_academica
                WHEN 'N' THEN 'REPROVADO'::situacao_academica
                ELSE 'REPROVADO_FREQUENCIA'::situacao_academica END,
       ROUND(a1 * 0.4 + a2 * 0.6, 2)
FROM notas;

