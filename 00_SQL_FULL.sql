  PRIMARY KEY ("tb_disciplina_id", "tb_requisito_id")
);

CREATE TABLE "tb_periodo_letivo" (
  "tb_periodo_letivo_id" SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "tb_periodo_letivo_ano" smallint NOT NULL,
  "tb_periodo_letivo_semestre" smallint NOT NULL,
  "tb_periodo_letivo_data_inicio" date NOT NULL,
  "tb_periodo_letivo_data_fim" date NOT NULL
