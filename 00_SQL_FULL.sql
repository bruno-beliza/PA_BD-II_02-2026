CREATE TABLE "tb_campus" (
  "tb_campus_id" SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "tb_campus_nome" varchar(60) UNIQUE NOT NULL,
  "tb_campus_cidade" varchar(60) NOT NULL,
  "tb_campus_uf" char(2) NOT NULL
);

CREATE TABLE "tb_curso" (
  "tb_curso_id" SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "tb_curso_codigo" varchar(10) UNIQUE NOT NULL,
  "tb_curso_nome" varchar(120) NOT NULL,
  "tb_curso_ch_total" smallint NOT NULL,
  "tb_curso_grau" varchar(20) NOT NULL
);

CREATE TABLE "tb_curso_campus" (
  "tb_curso_id" smallint,
  "tb_campus_id" smallint,
  PRIMARY KEY ("tb_curso_id", "tb_campus_id")
);

CREATE TABLE "tb_curriculo" (
  "tb_curriculo_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "tb_curso_id" smallint NOT NULL,
  "tb_curriculo_ano_vigencia" smallint NOT NULL,
  "tb_curriculo_ch_total_exigida" integer NOT NULL,
  "tb_curriculo_ativo" boolean NOT NULL DEFAULT true
);

CREATE TABLE "tb_disciplina" (
  "tb_disciplina_id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "tb_disciplina_codigo" varchar(10) UNIQUE NOT NULL,
  "tb_disciplina_nome" varchar(120) NOT NULL,
  "tb_disciplina_ch_teorica" smallint NOT NULL,
  "tb_disciplina_ch_pratica" smallint NOT NULL,
  "tb_disciplina_ch_total" smallint NOT NULL,
  "tb_disciplina_ementa" text
);

CREATE TABLE "tb_curriculo_disciplina" (
  "tb_curriculo_id" int,
  "tb_disciplina_id" int,
  "tb_curriculo_disciplina_periodo" smallint NOT NULL,
  "tb_curriculo_disciplina_tipo" tipo_disciplina NOT NULL,
  PRIMARY KEY ("tb_curriculo_id", "tb_disciplina_id")
);

CREATE TABLE "tb_disciplina_pre_requisito" (
  "tb_disciplina_id" int,
  "tb_requisito_id" int,
